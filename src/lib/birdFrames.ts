/**
 * The flight cycle, as twelve silhouettes.
 *
 * Generated rather than drawn: the wing is modelled as a tapered blade sweeping
 * from the shoulder, and the cycle sweeps its angle, its extension and its
 * curvature. That produced a shape worth keeping where freehand paths would not
 * have — the first attempts came out as fish.
 *
 * Three things carry the illusion, and all three come from watching real birds
 * rather than from geometry:
 *
 * 1. The wing is fully extended through the downstroke and folds on the way
 *    back up. A wing that keeps its length throughout reads as a windscreen
 *    wiper, not an animal.
 * 2. The downstroke takes a third of the cycle and the recovery two thirds,
 *    which is roughly the real proportion.
 * 3. Primaries are flexible, so the outer wing lags the stroke: raising the
 *    wing curls the tips upward, and they straighten as it comes down. Without
 *    it the wing is a rigid blade pivoting at the shoulder.
 *
 * Coordinates are in a 46x44 viewBox, facing left.
 */

